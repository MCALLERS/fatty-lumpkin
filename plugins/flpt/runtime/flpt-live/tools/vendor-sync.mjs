#!/usr/bin/env node
// vendor-sync.mjs · the trusted copies of flpt-live for pages that can't reach engine/ (PLAN §2.1, W1-07).
//
//   node engine/runtime/flpt-live/tools/vendor-sync.mjs           write app/src/renderer/vendor/flpt-live/ and site/vendor/flpt-live/
//   node engine/runtime/flpt-live/tools/vendor-sync.mjs --check   exit 1 when a copy drifts (the vendor-drift test)
//
// The app's CSP (script-src 'self') can't load engine/, and the landing page is its own site, so each gets byte-exact
// copies: the runtime, the inline host, the shared kits (one kits.js), VERSION, the MIT notice, and one small demo
// (demo/scene.js, its fonts embedded in demo/files.js, demo/demo.js defining it for FLPTInline) that proves the inline
// path under the app's CSP. Nothing else lives in those folders: extra files are removed (and fail --check).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { RUNTIME, ENGINE, isMain } from './lib.mjs';
import { kitsBundle } from './page.mjs';

export const REPO = join(ENGINE, '..');
export const TARGETS = [join(REPO, 'app', 'src', 'renderer', 'vendor', 'flpt-live'), join(REPO, 'site', 'vendor', 'flpt-live')];
const DEMO = join(RUNTIME, 'demos', 'counter');

/** relative path -> Buffer, exactly what every target folder must hold. */
export function expected() {
  const files = new Map();
  for (const f of ['flpt-live.js', 'host-inline.js', 'LICENSE-animate.md', 'VERSION']) files.set(f, readFileSync(join(RUNTIME, f)));
  files.set('kits.js', Buffer.from(kitsBundle()));
  files.set('demo/scene.js', readFileSync(join(DEMO, 'scene.js')));
  const fonts = {};
  const fdir = join(DEMO, 'assets', 'fonts');
  for (const f of readdirSync(fdir).filter((x) => /\.(ttf|otf)$/i.test(x)).sort()) fonts[f] = readFileSync(join(fdir, f)).toString('base64');
  files.set('demo/files.js', Buffer.from(`/* generated by vendor-sync.mjs: the counter demo's fonts (TrueType bytes for outline type). */\nFLPT.__files(${JSON.stringify({ fonts, pictures: [] })});\n`));
  for (const f of readdirSync(fdir).filter((x) => /\.txt$/i.test(x)).sort()) files.set(`demo/${f}`, readFileSync(join(fdir, f)));
  const beats = JSON.parse(readFileSync(join(DEMO, 'beats.json'), 'utf8'));
  files.set('demo/demo.js', Buffer.from(`/* generated by vendor-sync.mjs: the counter demo for FLPTInline (engine/runtime/flpt-live/demos/counter). */\nFLPTInline.define('counter', ${JSON.stringify({ scene: 'scene.js', files: 'files.js', duration: beats.duration, beats })});\n`));
  return files;
}

const walk = (d) => (existsSync(d) ? readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; }) : []);

/** Differences between a target folder and the expected files: [{ path, problem }]. */
export function check(target, want = expected()) {
  const out = [];
  for (const [rel, buf] of want) {
    const p = join(target, rel);
    if (!existsSync(p)) out.push({ path: rel, problem: 'missing' });
    else if (!readFileSync(p).equals(buf)) out.push({ path: rel, problem: 'differs' });
  }
  for (const p of walk(target)) { const rel = relative(target, p); if (!want.has(rel)) out.push({ path: rel, problem: 'extra' }); }
  return out;
}

export function sync(targets = TARGETS) {
  const want = expected();
  for (const t of targets) {
    for (const p of walk(t)) if (!want.has(relative(t, p))) rmSync(p);
    for (const [rel, buf] of want) {
      const p = join(t, rel);
      mkdirSync(dirname(p), { recursive: true });
      if (!existsSync(p) || !readFileSync(p).equals(buf)) writeFileSync(p, buf);
    }
  }
  return { files: want.size, targets: targets.map((t) => relative(REPO, t)) };
}

if (isMain(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const bad = TARGETS.flatMap((t) => check(t).map((d) => ({ ...d, target: relative(REPO, t) })));
    console.log(bad.length ? bad.map((d) => `${d.target}/${d.path}: ${d.problem}`).join('\n') : 'vendor copies: in sync');
    process.exit(bad.length ? 1 : 0);
  }
  console.log(JSON.stringify(sync()));
}
